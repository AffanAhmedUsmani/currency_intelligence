"""Probabilistic forecasting.

Deliberate scope decision (documented in README): we implement a bootstrap
Monte Carlo simulation over the currency's own historical daily log returns
as the primary forecast method, plus an optional Holt exponential-smoothing
point estimate as a secondary trend cross-check. We do NOT implement a full
GARCH or ARIMA fit.

Why: exchange rates are well-documented in the academic literature (going
back to Meese & Rogoff, 1983) to be extremely difficult to beat with a
structural or time-series model out-of-sample — a naive random walk is a
notoriously tough benchmark. Shipping an ARIMA/GARCH fit here would add
real complexity and give a false sense of sophistication without
demonstrated forecasting value for daily FX. The bootstrap approach makes
the same "no reliable directional edge" reality explicit instead of hiding
it behind a model that looks precise but isn't validated — the backtest
module (analytics/backtest.py) is what actually checks whether any of this
has predictive value, out-of-sample, and the API surfaces that result
alongside every forecast.
"""

from dataclasses import dataclass

import numpy as np
import pandas as pd


@dataclass
class ForecastResult:
    horizon_days: int
    expected_pct_move: float | None
    prob_appreciation: float | None
    prob_depreciation: float | None
    ci_low_pct: float | None
    ci_high_pct: float | None
    method: str
    confidence: str  # "insufficient_data" | "low" | "medium"
    secondary_trend_pct: float | None
    note: str


def bootstrap_forecast(
    log_returns: pd.Series, horizon_days: int = 30, n_sims: int = 5000
) -> ForecastResult:
    clean = log_returns.dropna()

    if len(clean) < 30:
        return ForecastResult(
            horizon_days=horizon_days,
            expected_pct_move=None,
            prob_appreciation=None,
            prob_depreciation=None,
            ci_low_pct=None,
            ci_high_pct=None,
            method="bootstrap_monte_carlo",
            confidence="insufficient_data",
            secondary_trend_pct=None,
            note="Not enough historical observations yet to produce a responsible forecast.",
        )

    rng = np.random.default_rng()
    sample = clean.to_numpy()
    sims = rng.choice(sample, size=(n_sims, horizon_days), replace=True)
    cumulative_log_return = sims.sum(axis=1)
    pct_moves = (np.exp(cumulative_log_return) - 1.0) * 100.0

    secondary_trend_pct = _holt_trend_forecast(clean, horizon_days)

    confidence = "low" if len(clean) < 90 else "medium"
    note = (
        "Generated by resampling this currency's own historical daily moves thousands of times "
        "(bootstrap simulation) — it describes a *range* of plausible outcomes based on past "
        "behavior, not a prediction of what will actually happen. Exchange rates behave close "
        "to a random walk, so treat the probability figures as weak evidence, not certainty. "
        "See the backtest results for whether this kind of estimate has had any real predictive "
        "value historically."
    )

    return ForecastResult(
        horizon_days=horizon_days,
        expected_pct_move=float(np.median(pct_moves)),
        prob_appreciation=float((pct_moves > 0).mean() * 100.0),
        prob_depreciation=float((pct_moves < 0).mean() * 100.0),
        ci_low_pct=float(np.percentile(pct_moves, 5)),
        ci_high_pct=float(np.percentile(pct_moves, 95)),
        method="bootstrap_monte_carlo",
        confidence=confidence,
        secondary_trend_pct=secondary_trend_pct,
        note=note,
    )


@dataclass
class HoldingPeriodOutcome:
    """Projected round-trip outcome of converting `amount` of the base
    currency into the target currency *now*, holding it, then converting
    back to the base currency after `horizon_days`.

    Built from the same bootstrap simulation as `bootstrap_forecast`, so the
    same "range of plausible outcomes, not a prediction" caveat applies.
    """

    label: str
    horizon_days: int
    expected_value: float | None
    expected_profit_loss: float | None
    expected_profit_loss_pct: float | None
    optimistic_value: float | None
    optimistic_profit_loss: float | None
    pessimistic_value: float | None
    pessimistic_profit_loss: float | None
    prob_profit_pct: float | None
    confidence: str
    note: str


def simulate_holding_period_outcomes(
    log_returns: pd.Series,
    amount: float,
    fee_pct: float,
    horizons_days: dict[str, int],
    n_sims: int = 4000,
) -> list[HoldingPeriodOutcome]:
    """For each (label, horizon_days) pair, simulates what `amount` of base
    currency converted to the target currency today would be worth in base
    currency if converted back after holding it for that many days.

    Math: if r(t) is the base->target rate (target units per 1 base unit,
    the same series everything else in this app uses) and the simulation
    draws a cumulative log return `c` over the horizon from the currency's
    own historical daily moves, then r(t+h) = r(t) * exp(c). Converting
    `amount` of base currency to target now and back to base later, paying
    the fee on both legs, gives:

        value_later = amount * (1 - fee)^2 / exp(c)

    Note r(t) itself cancels out — this is a property of a simple two-leg
    round trip through the same pair, not an approximation.
    """
    clean = log_returns.dropna()
    fee_mult_sq = (1.0 - fee_pct / 100.0) ** 2

    if len(clean) < 30:
        return [
            HoldingPeriodOutcome(
                label=label, horizon_days=h, expected_value=None, expected_profit_loss=None,
                expected_profit_loss_pct=None, optimistic_value=None, optimistic_profit_loss=None,
                pessimistic_value=None, pessimistic_profit_loss=None, prob_profit_pct=None,
                confidence="insufficient_data",
                note="Not enough historical observations yet for a responsible projection.",
            )
            for label, h in horizons_days.items()
        ]

    rng = np.random.default_rng()
    sample = clean.to_numpy()
    max_h = max(horizons_days.values())
    sims = rng.choice(sample, size=(n_sims, max_h), replace=True)
    cumulative_log_return = np.cumsum(sims, axis=1)

    confidence = "low" if len(clean) < 90 else "medium"
    note = (
        "Projected by resampling this currency's own historical daily moves thousands of times — "
        "a range of plausible round-trip outcomes based on past behavior, not a prediction. "
        "Assumes you pay the same fee/spread again converting back, and ignores any interest the "
        "held currency might separately earn."
    )

    results = []
    for label, h in sorted(horizons_days.items(), key=lambda kv: kv[1]):
        value_later = amount * fee_mult_sq * np.exp(-cumulative_log_return[:, h - 1])
        profit = value_later - amount

        results.append(
            HoldingPeriodOutcome(
                label=label,
                horizon_days=h,
                expected_value=float(np.median(value_later)),
                expected_profit_loss=float(np.median(profit)),
                expected_profit_loss_pct=float(np.median(profit) / amount * 100.0),
                optimistic_value=float(np.percentile(value_later, 95)),
                optimistic_profit_loss=float(np.percentile(profit, 95)),
                pessimistic_value=float(np.percentile(value_later, 5)),
                pessimistic_profit_loss=float(np.percentile(profit, 5)),
                prob_profit_pct=float((profit > 0).mean() * 100.0),
                confidence=confidence,
                note=note,
            )
        )
    return results


def _holt_trend_forecast(log_returns: pd.Series, horizon_days: int) -> float | None:
    """Secondary, explicitly-labeled-supplementary trend extrapolation via
    Holt's linear exponential smoothing. Wrapped defensively: short or
    degenerate series can fail to fit, in which case we simply omit it
    rather than raising or fabricating a number.
    """
    try:
        from statsmodels.tsa.holtwinters import Holt

        level_series = log_returns.cumsum()
        if len(level_series) < 20 or level_series.nunique() < 5:
            return None
        model = Holt(level_series.to_numpy(), initialization_method="estimated").fit(optimized=True)
        forecast_log_level = model.forecast(horizon_days)[-1]
        current_log_level = level_series.iloc[-1]
        return float((np.exp(forecast_log_level - current_log_level) - 1.0) * 100.0)
    except Exception:
        return None
